// 일주(Day Pillar) 계산 — KST 기준. 기준일: 2000-01-01 = 戊午(index 54)
export function getIlju(y, m, d, hour) {
  let dayShift = 0;
  if (typeof hour === "number" && hour >= 23) dayShift = 1; // 야자시: 23시 이후는 다음 일주
  const days = Math.round((Date.UTC(y, m - 1, d) - Date.UTC(2000, 0, 1)) / 86400000) + dayShift;
  const idx = (((days + 54) % 60) + 60) % 60;
  const stem = STEMS[idx % 10], branch = BRANCHES[idx % 12];
  const kr = stem + branch;
  return {
    idx, kr, stem, branch,
    hanja: STEM_HANJA[stem] + BRANCH_HANJA[branch],
    element: ELEMENT[stem],
    profile: ILJU[kr]
  };
}
